-- Plusieurs utilisateurs : comptes, sessions en base, invitations. Toute la progression existante
-- est rattachée au compte du propriétaire (id 1) ; son email et son mot de passe sont posés au
-- démarrage depuis BTD_ADMIN_EMAIL / BTD_ADMIN_PASSWORD (voir service.EnsureOwner).

-- +goose Up
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL, -- toujours en minuscules
    display_name VARCHAR(40) NOT NULL,
    password_hash TEXT NOT NULL, -- vide : compte pas encore réclamé, connexion impossible
    is_admin BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_key ON users (email);

